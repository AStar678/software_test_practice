-- Constraint names in historical installations may have been generated by MySQL. Discover them
-- by their columns, not a guessed auto-generated name. All values come from local metadata.
SET @cleanup_drops := (SELECT GROUP_CONCAT(DISTINCT CONCAT('DROP FOREIGN KEY `',constraint_name,'`'))
 FROM information_schema.key_column_usage WHERE constraint_schema=DATABASE() AND table_name='users'
 AND referenced_table_name IS NOT NULL AND column_name IN ('team_id','manager_id','department_id','position_id'));
SET @cleanup_sql := CONCAT('ALTER TABLE users ',@cleanup_drops);
PREPARE cleanup_statement FROM @cleanup_sql;
EXECUTE cleanup_statement;
DEALLOCATE PREPARE cleanup_statement;

SET @cleanup_drops := (SELECT GROUP_CONCAT(CONCAT('DROP CHECK `',tc.constraint_name,'`'))
 FROM information_schema.table_constraints tc JOIN information_schema.check_constraints cc
 ON cc.constraint_schema=tc.constraint_schema AND cc.constraint_name=tc.constraint_name
 WHERE tc.constraint_schema=DATABASE() AND tc.table_name='users'
 AND (cc.check_clause LIKE '%`role`%' OR cc.check_clause LIKE '%`rank_level`%'));
SET @cleanup_sql := CONCAT('ALTER TABLE users ',@cleanup_drops);
PREPARE cleanup_statement FROM @cleanup_sql;
EXECUTE cleanup_statement;
DEALLOCATE PREPARE cleanup_statement;
ALTER TABLE users DROP COLUMN username, DROP COLUMN role, DROP COLUMN rank_level,
 DROP COLUMN manager_id, DROP COLUMN team_id, DROP COLUMN department_id, DROP COLUMN position_id;

SET @cleanup_drops := (SELECT GROUP_CONCAT(DISTINCT CONCAT('DROP FOREIGN KEY `',constraint_name,'`'))
 FROM information_schema.key_column_usage WHERE constraint_schema=DATABASE() AND table_name='teams'
 AND referenced_table_name IS NOT NULL AND column_name IN ('parent_id','lead_user_id'));
SET @cleanup_sql := CONCAT('ALTER TABLE teams ',@cleanup_drops);
PREPARE cleanup_statement FROM @cleanup_sql;
EXECUTE cleanup_statement;
DEALLOCATE PREPARE cleanup_statement;
ALTER TABLE teams DROP COLUMN parent_id, DROP COLUMN lead_user_id;

SET @cleanup_drops := (SELECT GROUP_CONCAT(DISTINCT CONCAT('DROP FOREIGN KEY `',constraint_name,'`'))
